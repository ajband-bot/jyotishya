        assert evaluations["DSH-007"].matched == ctx["doshas"]["pitru_dosha"]["present"]
        assert evaluations["DSH-009"].matched == ctx["doshas"]["guru_chandala"]["present"]
        assert evaluations["DSH-013"].matched == ctx["doshas"]["papakartari"]["present"]
        assert evaluations["DSH-015"].matched == ctx["transits"]["saturn_assessment"]["sade_sati"]["active"]
        for evaluation in evaluations.values():
            assert evaluation.quality != "data_gap"


