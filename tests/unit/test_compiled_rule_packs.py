def test_dosha_rules_agree_with_direct_doshas_dict_for_every_fixture():
    """Cross-check: whatever DSH-001 (mangal dosha present) reports must
    exactly match ctx['doshas']['mangal_dosha']['present'] -- no drift
    between the v2 rule wrapper and the underlying computed truth."""
    rules = [r for r in load_compiled_rule_packs(COMPILED_DIR) if r.id.startswith("DSH-")]
