def _by_category(rules: list[Rule], category: str) -> list[Rule]:
    return [r for r in rules if r.category == category]


def test_all_compiled_packs_load_and_validate():
    rules = load_compiled_rule_packs()
    # Grand total drifts as new packs land (Phase 4 added yoga_v2.yaml,
    # nakshatra_v2.yaml, ...) -- rather than hardcode a number that goes
    # stale every time, verify the total equals the sum of each known
    # prefix's own count, and that no rule id is unaccounted for.
    prefix_counts = {
        "PIH-": 108, "LPH-": 144, "PIS-": 108, "DSH-": 15, "YOG-": 18, "NAK-": 27, "DASHA-": 81,
        "MAR-": 40, "CAR-": 30, "REM-": 20,
    }
    for prefix, expected in prefix_counts.items():
        actual = sum(1 for r in rules if r.id.startswith(prefix))
        assert actual == expected, f"{prefix}: expected {expected}, got {actual}"
    assert len(rules) == sum(prefix_counts.values())


