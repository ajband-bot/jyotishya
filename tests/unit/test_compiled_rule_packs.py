def test_exactly_9_planet_in_house_rules_match_per_fixture():
    """Every planet occupies exactly one house -> exactly 9 of the 108
    PIH rules should match, one per planet, and each should report
    quality=computed (classical rules, no synthesis discount)."""
    rules = [r for r in load_compiled_rule_packs(COMPILED_DIR) if r.id.startswith("PIH-")]
    for fixture_id in list_fixture_ids():
        ctx = _context(fixture_id)
        evaluations = evaluate_rule_set(rules, ctx)
        matched = [e for e in evaluations if e.matched]
        assert len(matched) == 9, f"{fixture_id}: expected 9 matches, got {len(matched)}"
        assert all(e.quality == "computed" for e in matched)
        matched_planets = {e.outputs[0].payload["planet"] for e in matched}
        assert matched_planets == {"Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn", "Rahu", "Ketu"}
        for evaluation in matched:
            planet = evaluation.outputs[0].payload["planet"]
            house = evaluation.outputs[0].payload["house"]
            assert ctx["chart"][planet]["house"] == house


