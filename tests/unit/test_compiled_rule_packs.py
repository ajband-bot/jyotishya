def test_remedy_nogem_rules_agree_with_direct_remedies_dict_for_every_fixture():
    """Safety-critical cross-check: REM-NOGEM-<CODE> must exactly match
    ctx['remedies']['planets'][planet]['gemstone_contraindicated'] -- no
    drift between the v2 rule wrapper and the underlying safety gate."""
    rules = [r for r in load_compiled_rule_packs(COMPILED_DIR) if r.id.startswith("REM-NOGEM-")]
    code_to_planet = {"SUN": "Sun", "MOO": "Moon", "MAR": "Mars", "MER": "Mercury", "JUP": "Jupiter",
                       "VEN": "Venus", "SAT": "Saturn", "RAH": "Rahu", "KET": "Ketu"}
    for fixture_id in list_fixture_ids():
        ctx = _context(fixture_id)
        evaluations = {e.rule_id: e for e in evaluate_rule_set(rules, ctx)}
        for rule in rules:
            code = rule.id.replace("REM-NOGEM-", "")
            planet = code_to_planet[code]
            expected = ctx["remedies"]["planets"][planet]["gemstone_contraindicated"]
            assert evaluations[rule.id].matched == expected, f"{fixture_id}:{rule.id}"


